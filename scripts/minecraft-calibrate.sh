terminate_minecraft_on_device() {
    local device_id="$1"
    local processes_json="$OUTPUT_DIR/minecraft-processes.json"
    local processes_log="$OUTPUT_DIR/minecraft-processes.log"
    if ! xcrun devicectl device info processes \
        --device "$device_id" \
        --timeout 15 \
        --json-output "$processes_json" \
        --log-output "$processes_log" \
        >/dev/null 2>&1; then
        echo "warning: could not list device processes; skipping Minecraft termination" >&2
        return 0
    fi
    local pids
    pids="$(jq -r --arg bundle "$MINECRAFT_BUNDLE_ID" '
        .. | objects
        | select(
            ((.bundleIdentifier? // .bundleID? // .applicationIdentifier? // "") == $bundle)
            or ((.executable? // "") | test("/Minecraft[.]app/Minecraft$|minecraftpe"; "i"))
        )
        | (.pid? // .processIdentifier? // empty)
    ' "$processes_json" | sort -u)"
    if [[ -z "$pids" ]]; then
        echo "Minecraft is not running." | tee -a "$TRANSCRIPT"
        return 0
    fi
    local pid
    for pid in $pids; do
        echo "Terminating Minecraft process $pid..." | tee -a "$TRANSCRIPT"
        xcrun devicectl device process terminate \
            --device "$device_id" \
            --pid "$pid" \
            --kill \
            --timeout 15 \
            >/dev/null || true
    done
}

cmd_stop() {
    local keep_state="no" delete_world="no"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --keep-state) keep_state="yes"; shift ;;
            --delete-world|--fresh-world) delete_world="yes"; shift ;;
            --keep-world) delete_world="no"; shift ;;
            *) echo "error: unknown argument '$1' for stop" >&2; exit 1 ;;
        esac
    done
    if [[ "$keep_state" == "yes" && "$delete_world" == "yes" ]]; then
        echo "error: --keep-state and --delete-world are mutually exclusive" >&2
        exit 1
    fi

    if [[ ! -f "$SESSION_FILE" ]]; then
        echo "error: no active calibration session to stop." >&2
        exit 1
    fi

    local device_id xcodebuild_pid iproxy_pid
    device_id="$(jq -r '.device_id // empty' "$SESSION_FILE" 2>/dev/null || true)"
    xcodebuild_pid="$(jq -r '.xcodebuild_pid // empty' "$SESSION_FILE" 2>/dev/null || true)"
    iproxy_pid="$(jq -r '.iproxy_pid // empty' "$SESSION_FILE" 2>/dev/null || true)"

    echo "Stopping calibration session..." | tee -a "$TRANSCRIPT"

    # Kill iproxy
    if [[ -n "$iproxy_pid" ]] && kill -0 "$iproxy_pid" 2>/dev/null; then
        echo "Terminating iproxy ($iproxy_pid)..." | tee -a "$TRANSCRIPT"
        kill "$iproxy_pid" 2>/dev/null || true
        sleep 1
        kill -9 "$iproxy_pid" 2>/dev/null || true
    fi
    rm -f "$IPROXY_PID_FILE"

    # Kill xcodebuild
    if [[ -n "$xcodebuild_pid" ]] && kill -0 "$xcodebuild_pid" 2>/dev/null; then
        echo "Terminating xcodebuild ($xcodebuild_pid)..." | tee -a "$TRANSCRIPT"
        kill "$xcodebuild_pid" 2>/dev/null || true
        sleep 2
        kill -9 "$xcodebuild_pid" 2>/dev/null || true
        # Also kill any child test runner processes
        pkill -P "$xcodebuild_pid" 2>/dev/null || true
    fi
    rm -f "$XCODEBUILD_PID_FILE"

    # Give device time to settle
    sleep 2

    if [[ "$keep_state" == "yes" ]]; then
        echo "Keeping Minecraft, packs, and world untouched (--keep-state)." | tee -a "$TRANSCRIPT"
    else
        if [[ -n "$device_id" ]]; then
            terminate_minecraft_on_device "$device_id"
            if [[ "$delete_world" == "yes" ]]; then
                echo "Running AFC cleanup (Generated by Craftberry packs + craftberry test world, INCLUDING world deletion)..." | tee -a "$TRANSCRIPT"
                set +e
                "$CLEANUP_SCRIPT" clean --delete-world --yes >> "$TRANSCRIPT" 2>&1
                local cleanup_status=$?
                set -e
            else
                echo "Running AFC cleanup (Generated by Craftberry packs only, world preserved)..." | tee -a "$TRANSCRIPT"
                set +e
                "$CLEANUP_SCRIPT" clean --yes >> "$TRANSCRIPT" 2>&1
                local cleanup_status=$?
                set -e
            fi
            if [[ $cleanup_status -ne 0 ]]; then
                echo "warning: AFC cleanup failed with status $cleanup_status — check $TRANSCRIPT" >&2
            else
                echo "AFC cleanup complete." | tee -a "$TRANSCRIPT"
            fi
        else
            echo "warning: device_id unknown, skipping Minecraft termination and AFC cleanup" >&2
        fi
    fi

    # Preserve logs, remove session file
    echo "Session stopped. Logs kept under $OUTPUT_DIR" | tee -a "$TRANSCRIPT"
    rm -f "$SESSION_FILE"
}

main() {
    mkdir -p "$OUTPUT_DIR" "$RESULT_BUNDLE_DIR" "$SCREENSHOT_DIR"
    case "${1:-}" in
        start)
            shift
            cmd_start "$@"
            ;;
        status)
            cmd_status
            ;;
        list-steps|list_steps)
            cmd_list_steps
            ;;
        observe)
            shift
            cmd_observe "$@"
            ;;
        step)
            cmd_simple '{"command":"step"}' "step"
            ;;
        run-until|run_until)
            if [[ $# -lt 2 ]]; then echo "error: run-until requires <id-or-name>" >&2; exit 1; fi
            local target="${2:-}"
            if [[ -z "$target" ]]; then echo "error: run-until requires <id-or-name>" >&2; exit 1; fi
            local req
            req="$(python3 -c "import json, sys; print(json.dumps({'command':'run_until','target':sys.argv[1]}))" "$target")"
            cmd_simple "$req" "run-until"
            ;;
        mark-complete|mark_complete)
            cmd_simple '{"command":"mark_complete"}' "mark-complete"
            ;;
        select-step|select_step)
            if [[ $# -lt 2 ]]; then echo "error: select-step requires <id-or-name>" >&2; exit 1; fi
            local target="${2:-}"
            local req2
            req2="$(python3 -c "import json, sys; print(json.dumps({'command':'select_step','target':sys.argv[1]}))" "$target")"
            cmd_simple "$req2" "select-step"
            ;;
        tap)
            shift
            cmd_tap "$@"
            ;;
        drag)
            shift
            cmd_drag "$@"
            ;;
        swipe-up|swipe_up)
            cmd_swipe_up
            ;;
        keyboard-text|keyboard_text)
            shift
            cmd_keyboard_text "$@"
            ;;
        numeric-keyboard-text|numeric_keyboard_text)
            shift
            cmd_numeric_keyboard_text "$@"
            ;;
        chat-command|chat_command)
            shift
            cmd_chat_command "$@"
            ;;
        wait)
            shift
            cmd_wait "$@"
            ;;
        stop)
            shift
            cmd_stop "$@"
            ;;
        -h|--help|help|"")
            usage
            ;;
        *)
            echo "error: unknown command '$1'" >&2
            usage >&2
            exit 1
            ;;
    esac
}

main "$@"
