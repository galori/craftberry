#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_DIR="$ROOT_DIR/.build/minecraft-cleanup"
BUNDLE_ID="com.mojang.minecraftpe"
WORLD_NAME="${CRAFTBERRY_CLEANUP_WORLD_NAME:-craftberry test}"
WORLD_MATCH_MODE="${CRAFTBERRY_CLEANUP_WORLD_MATCH_MODE:-contains}"
PACK_CLEANUP_SCOPE="${CRAFTBERRY_CLEANUP_PACK_SCOPE:-all}"
CRAFTBERRY_MARKER="Generated by Craftberry"
# Confirmed live: afcclient's --documents house-arrest root is one level
# above what Finder's file-sharing pane displays — Finder shows the
# contents of "Documents/", not the house-arrest root itself.
AFC_BASE="Documents/games/com.mojang"
WORLD_DIR_NAMES=""
MATCHING_WORLD_DIR_NAMES=""

usage() {
    cat <<USAGE
Usage: scripts/minecraft-cleanup.sh <status|clean> [--delete-world] [--keep-world] [--yes]

Set CRAFTBERRY_CLEANUP_WORLD_NAME to select the world name. World matching
defaults to contains for the shared "craftberry test" world. Set
CRAFTBERRY_CLEANUP_WORLD_MATCH_MODE=exact for prepared-world E2E cleanup.
Set CRAFTBERRY_CLEANUP_PACK_SCOPE=referenced with exact matching to remove
only generated packs used by that world and by no other world. The default
scope 'all' preserves the existing full cleanup behavior.
Exact-name cleanup reads every world title and aborts on unreadable titles or
duplicate target names. Referenced cleanup also aborts on incomplete listings
or unreadable pack-reference files.

Cleans up Craftberry-generated Minecraft Bedrock test packs directly from
Minecraft's shared Documents directory on the connected iPhone, using
afcclient (part of libimobiledevice) to talk to the device's AFC/House
Arrest service directly — no macFUSE, no kernel extension, no Recovery
Mode / Reduced Security changes required. This bypasses Minecraft's own
in-game pack-removal UI entirely, which can only deactivate a pack for one
world, never uninstall it from the device (see docs/CLEANUP_HANDOFF.md).

The E2E harness now reuses the "$WORLD_NAME" world across runs. The default
'clean --yes' keeps that world and only deactivates/deletes the packs (reset
world_behavior_packs.json / world_resource_packs.json to [] and removes the
Generated by Craftberry pack folders). Pass --delete-world to also nuke the
world directory itself — used only for manual recovery or before a fresh-world
run.

Modes:
  status   Read-only. Lists every installed behavior/resource pack, whether
           its manifest carries the Craftberry-generated marker, and
           whether any matching "$WORLD_NAME" world references it. Set
           CRAFTBERRY_CLEANUP_WORLD_NAME to inspect a different world. Changes
           nothing.
  clean    Deletes Craftberry-generated pack folders (manifest description
           "$CRAFTBERRY_MARKER") from behavior_packs/ and resource_packs/.
           With the default 'all' scope, deletes every such pack. With the
           'referenced' scope, deletes only packs used exclusively by the
           exact selected world. If matching worlds exist, also resets their
           pack-reference files to [].
           With --delete-world, permanently deletes every matching
           "$WORLD_NAME" world directory instead of preserving it. Matching
           uses the configured mode. Requires --yes. --keep-world is an
           explicit alias for the default (preserve world) and is accepted
           for clarity.

Requires: afcclient (brew tap gromgit/fuse && brew install ifuse-mac pulls
it in as a libimobiledevice dependency), jq.

Constraints:
  - Minecraft must be fully quit on the device first — confirmed live that
    AFC's view of Minecraft's own directories is unreliable while the app
    is running (e.g. minecraftWorlds can appear empty). This script does
    not check that for you; quit Minecraft (or
    'xcrun devicectl device process terminate --device <id> --pid <pid>')
    before running either mode.
  - Never touches a pack folder without the exact Craftberry marker.
  - Never deletes the world directory unless clean is run with both
    --delete-world and --yes.
USAGE
}

require_tool() {
    if ! command -v "$1" >/dev/null 2>&1; then
        echo "error: required tool '$1' was not found on PATH" >&2
        exit 1
    fi
}

afc() {
    # Confirmed live: afcclient's getopt-style parser reorders arguments and
    # trips over subcommand flags like `rm -rf` (misreads -rf as an unknown
    # top-level option) unless `--` explicitly stops option parsing first.
    afcclient --documents "$BUNDLE_ID" -- "$@"
}

# Lists immediate child names of an AFC directory, one per line.
afc_ls() {
    afc ls "$1"
}

# Downloads a remote file to a local temp path; prints the local path, or
# nothing (and a non-zero exit) if it doesn't exist / can't be read.
afc_get_to_temp() {
    local remote="$1" local_name="$2" local_path
    local_path="$OUTPUT_DIR/tmp/$local_name"
    mkdir -p "$(dirname "$local_path")"
    rm -f "$local_path"
    if afc get "$remote" "$local_path" >/dev/null 2>&1 && [[ -f "$local_path" ]]; then
        printf '%s\n' "$local_path"
        return 0
    fi
    return 1
}

find_world_dir_names() {
    local listing name dir level_name level_file
    WORLD_DIR_NAMES=""
    MATCHING_WORLD_DIR_NAMES=""
    if ! listing="$(afc_ls "$AFC_BASE/minecraftWorlds")"; then
        echo "error: could not list Minecraft world directories; refusing cleanup." >&2
        return 1
    fi
    WORLD_DIR_NAMES="$listing"

    for name in $listing; do
        dir="$AFC_BASE/minecraftWorlds/$name"
        if level_file="$(afc_get_to_temp "$dir/levelname.txt" "levelname-$name.txt")"; then
            level_name="$(cat "$level_file")"
        else
            if [[ "$WORLD_MATCH_MODE" == "exact" ]]; then
                echo "error: could not read the title for world directory '$name'; refusing exact-name cleanup." >&2
                return 1
            fi
            continue
        fi

        if [[ "$WORLD_MATCH_MODE" == "exact" && -z "$level_name" ]]; then
            echo "error: world directory '$name' has an empty title; refusing exact-name cleanup." >&2
            return 1
        fi
        if [[ ( "$WORLD_MATCH_MODE" == "exact" && "$level_name" == "$WORLD_NAME" ) \
            || ( "$WORLD_MATCH_MODE" == "contains" && "$level_name" == *"$WORLD_NAME"* ) ]]; then
            if [[ -z "$MATCHING_WORLD_DIR_NAMES" ]]; then
                MATCHING_WORLD_DIR_NAMES="$name"
            else
                MATCHING_WORLD_DIR_NAMES+=$'\n'"$name"
            fi
        fi
    done
}

pack_ids_referenced_by_world() {
    local world_dir="$1" file="$2" local_path
    if local_path="$(afc_get_to_temp "$world_dir/$file" "$(basename "$world_dir")-$file")"; then
        jq -r '.[]?.pack_id' "$local_path" 2>/dev/null
    fi
}

read_pack_ids_for_cleanup() {
    local world_dir="$1" file="$2" directory_listing local_path
    if ! directory_listing="$(afc_ls "$world_dir")"; then
        return 1
    fi
    if ! grep -Fxq -- "$file" <<<"$directory_listing"; then
        return 0
    fi
    if ! local_path="$(afc_get_to_temp "$world_dir/$file" "$(basename "$world_dir")-$file")"; then
        return 1
    fi
    jq -r -s '
        if length != 1 or (.[0] | type) != "array" then
            error("expected exactly one pack reference array")
        else
            .[0][]
        end
        | if (.pack_id | type) == "string" and (.pack_id | length) > 0 then
            .pack_id
        else
            error("invalid pack_id")
        end
    ' "$local_path"
}

report_packs() {
    local kind="$1" active_ids="$2" names
    local name manifest_local uuid pack_name description marker active
    if ! names="$(afc_ls "$AFC_BASE/${kind}_packs")"; then
        echo "error: could not list installed $kind packs." >&2
        return 1
    fi
    for name in $names; do
        if ! manifest_local="$(afc_get_to_temp "$AFC_BASE/${kind}_packs/$name/manifest.json" "${kind}-$name-manifest.json")"; then
            continue
        fi
        pack_name="$(jq -r '.header.name // "?"' "$manifest_local" 2>/dev/null)"
        uuid="$(jq -r '.header.uuid // "?"' "$manifest_local" 2>/dev/null)"
        description="$(jq -r '.header.description // ""' "$manifest_local" 2>/dev/null)"
        marker="not Craftberry-generated — SKIPPED by clean"
        if [[ "$description" == "$CRAFTBERRY_MARKER" ]]; then
            marker="Craftberry-generated"
        fi
        active=""
        if [[ -n "$active_ids" ]] && grep -qx "$uuid" <<<"$active_ids"; then
            active=" [ACTIVE in $WORLD_NAME]"
        fi
        printf '  %-16s %-38s %-28s %s%s\n' "$name" "$uuid" "$marker" "$pack_name" "$active"
    done
}

cmd_status() {
    local world_names active_behavior="" active_resource=""
    if ! find_world_dir_names; then return 1; fi
    world_names="$MATCHING_WORLD_DIR_NAMES"
    if [[ -n "$world_names" ]]; then
        local world_name world_dir
        echo "Worlds: $WORLD_NAME"
        for world_name in $world_names; do
            world_dir="$AFC_BASE/minecraftWorlds/$world_name"
            echo "  $world_dir"
            active_behavior="$active_behavior"$'\n'"$(pack_ids_referenced_by_world "$world_dir" "world_behavior_packs.json")"
            active_resource="$active_resource"$'\n'"$(pack_ids_referenced_by_world "$world_dir" "world_resource_packs.json")"
        done
    else
        echo "Worlds: $WORLD_NAME not found (nothing currently references installed packs)"
    fi
    echo ""

    echo "=== Installed behavior packs ==="
    report_packs "behavior" "$active_behavior"
    echo ""
    echo "=== Installed resource packs ==="
    report_packs "resource" "$active_resource"
}

cmd_clean() {
    local confirmed="$1" delete_world="$2"
    local world_names="" all_world_dirs
    if ! find_world_dir_names; then return 1; fi
    world_names="$MATCHING_WORLD_DIR_NAMES"
    all_world_dirs="$WORLD_DIR_NAMES"

    local target_behavior="" target_resource="" protected_behavior="" protected_resource=""
    if [[ "$WORLD_MATCH_MODE" == "exact" && -n "$world_names" ]]; then
        local target_count
        target_count="$(printf '%s\n' "$world_names" | awk 'NF { count++ } END { print count + 0 }')"
        if [[ "$target_count" -gt 1 ]]; then
            echo "error: exact world name '$WORLD_NAME' matched $target_count worlds; refusing ambiguous cleanup." >&2
            return 1
        fi
    fi

    if [[ "$PACK_CLEANUP_SCOPE" == "referenced" && -n "$world_names" ]]; then
        local world_name world_dir behavior_ids resource_ids
        for world_name in $all_world_dirs; do
            world_dir="$AFC_BASE/minecraftWorlds/$world_name"
            if ! behavior_ids="$(read_pack_ids_for_cleanup "$world_dir" "world_behavior_packs.json")" \
                || ! resource_ids="$(read_pack_ids_for_cleanup "$world_dir" "world_resource_packs.json")"; then
                echo "error: could not read or validate pack references for world '$world_name'; refusing cleanup." >&2
                return 1
            fi
            if [[ "$world_name" == "$world_names" ]]; then
                target_behavior="$behavior_ids"
                target_resource="$resource_ids"
            else
                protected_behavior="$protected_behavior"$'\n'"$behavior_ids"
                protected_resource="$protected_resource"$'\n'"$resource_ids"
            fi
        done
    fi

    local behavior_pack_names resource_pack_names
    if ! behavior_pack_names="$(afc_ls "$AFC_BASE/behavior_packs")"; then
        echo "error: could not list behavior packs; refusing cleanup." >&2
        return 1
    fi
    if ! resource_pack_names="$(afc_ls "$AFC_BASE/resource_packs")"; then
        echo "error: could not list resource packs; refusing cleanup." >&2
        return 1
    fi

    if [[ "$confirmed" != "yes" ]]; then
        if [[ "$PACK_CLEANUP_SCOPE" == "referenced" ]]; then
            echo "This would permanently delete Craftberry-generated pack folders referenced only by '$WORLD_NAME' under:"
        else
            echo "This would permanently delete every Craftberry-generated pack folder under:"
        fi
        echo "  $AFC_BASE/behavior_packs"
        echo "  $AFC_BASE/resource_packs"
        if [[ -n "$world_names" ]]; then
            if [[ "$delete_world" == "yes" ]]; then
                echo "and permanently delete every matching $WORLD_NAME world:"
                local world_name
                for world_name in $world_names; do
                    echo "  $AFC_BASE/minecraftWorlds/$world_name"
                done
            else
                echo "and reset every matching $WORLD_NAME world's world_behavior_packs.json / world_resource_packs.json to []:"
                local world_name
                for world_name in $world_names; do
                    echo "  $AFC_BASE/minecraftWorlds/$world_name"
                done
            fi
        else
            echo "($WORLD_NAME does not currently exist, so there are no worlds to reset or delete.)"
        fi
        echo ""
        echo "Run 'status' first to review, then re-run with --yes to actually do this."
        exit 1
    fi

    local removed_worlds=0
    if [[ -n "$world_names" ]]; then
        local world_name world_dir
        for world_name in $world_names; do
            world_dir="$AFC_BASE/minecraftWorlds/$world_name"
            if [[ "$delete_world" == "yes" ]]; then
                echo "Removing world: $WORLD_NAME ($world_dir)"
                afc rm -rf "$world_dir"
                removed_worlds=$((removed_worlds + 1))
            else
                echo "Resetting $WORLD_NAME's pack reference lists: $world_dir"
                printf '[]' > "$OUTPUT_DIR/tmp/empty.json"
                afc put "$OUTPUT_DIR/tmp/empty.json" "$world_dir/world_behavior_packs.json" >/dev/null
                afc put "$OUTPUT_DIR/tmp/empty.json" "$world_dir/world_resource_packs.json" >/dev/null
            fi
        done
    fi

    local removed=0 kept=0 skipped=0
    local kind name names manifest_local description uuid target_ids protected_ids
    for kind in behavior resource; do
        if [[ "$kind" == "behavior" ]]; then
            target_ids="$target_behavior"
            protected_ids="$protected_behavior"
        else
            target_ids="$target_resource"
            protected_ids="$protected_resource"
        fi
        if [[ "$kind" == "behavior" ]]; then
            names="$behavior_pack_names"
        else
            names="$resource_pack_names"
        fi
        for name in $names; do
            if ! manifest_local="$(afc_get_to_temp "$AFC_BASE/${kind}_packs/$name/manifest.json" "${kind}-$name-manifest.json")"; then
                continue
            fi
            description="$(jq -r '.header.description // ""' "$manifest_local" 2>/dev/null)"
            if [[ "$description" == "$CRAFTBERRY_MARKER" ]]; then
                if [[ "$PACK_CLEANUP_SCOPE" == "referenced" ]]; then
                    uuid="$(jq -r '.header.uuid // ""' "$manifest_local" 2>/dev/null)"
                    if [[ -z "$target_ids" ]] || ! grep -Fxq -- "$uuid" <<<"$target_ids"; then
                        skipped=$((skipped + 1))
                        continue
                    fi
                    if [[ -n "$protected_ids" ]] && grep -Fxq -- "$uuid" <<<"$protected_ids"; then
                        echo "Keeping $kind pack referenced by another world: $name"
                        skipped=$((skipped + 1))
                        continue
                    fi
                fi
                echo "Removing $kind pack: $name"
                afc rm -rf "$AFC_BASE/${kind}_packs/$name"
                removed=$((removed + 1))
            else
                kept=$((kept + 1))
            fi
        done
    done

    echo ""
    echo "Removed $removed Craftberry-generated pack folder(s); left $kept non-Craftberry folder(s) untouched."
    if [[ "$PACK_CLEANUP_SCOPE" == "referenced" ]]; then
        echo "Preserved $skipped generated pack folder(s) outside the selected world's exclusive references."
    fi
    if [[ "$delete_world" == "yes" ]]; then
        echo "Removed $removed_worlds matching $WORLD_NAME world(s)."
    fi
}

main() {
    local mode="${1:-}"
    shift || true

    case "$mode" in
        -h|--help|help|"")
            usage
            exit 0
            ;;
    esac

    local confirmed="no" delete_world="no"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --yes)
                confirmed="yes"
                shift
                ;;
            --delete-world)
                delete_world="yes"
                shift
                ;;
            --keep-world)
                delete_world="no"
                shift
                ;;
            *)
                echo "error: unknown argument '$1'" >&2
                usage
                exit 1
                ;;
        esac
    done

    case "$mode" in
        status|clean) ;;
        *)
            echo "error: unknown mode '$mode'" >&2
            usage
            exit 1
            ;;
    esac

    case "$WORLD_MATCH_MODE" in
        contains|exact) ;;
        *)
            echo "error: CRAFTBERRY_CLEANUP_WORLD_MATCH_MODE must be 'contains' or 'exact' (got '$WORLD_MATCH_MODE')" >&2
            exit 1
            ;;
    esac

    case "$PACK_CLEANUP_SCOPE" in
        all|referenced) ;;
        *)
            echo "error: CRAFTBERRY_CLEANUP_PACK_SCOPE must be 'all' or 'referenced' (got '$PACK_CLEANUP_SCOPE')" >&2
            exit 1
            ;;
    esac
    if [[ "$PACK_CLEANUP_SCOPE" == "referenced" && "$WORLD_MATCH_MODE" != "exact" ]]; then
        echo "error: referenced pack cleanup requires CRAFTBERRY_CLEANUP_WORLD_MATCH_MODE=exact" >&2
        exit 1
    fi

    if [[ "$mode" != "clean" && "$delete_world" == "yes" ]]; then
        echo "error: --delete-world can only be used with clean" >&2
        usage
        exit 1
    fi

    require_tool jq
    require_tool afcclient
    mkdir -p "$OUTPUT_DIR/tmp"

    case "$mode" in
        status)
            cmd_status
            ;;
        clean)
            cmd_clean "$confirmed" "$delete_world"
            ;;
    esac
}

main "$@"
