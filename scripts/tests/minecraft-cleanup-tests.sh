#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRATCH_DIR="$ROOT_DIR/.scratch"
mkdir -p "$SCRATCH_DIR"
TEST_ROOT="$(mktemp -d "$SCRATCH_DIR/minecraft-cleanup-tests.XXXXXX")"
MOCK_BIN="$TEST_ROOT/bin"
CLEANUP_SCRIPT="$ROOT_DIR/scripts/minecraft-cleanup.sh"
WORLD_PATH="Documents/games/com.mojang/minecraftWorlds"
BEHAVIOR_PATH="Documents/games/com.mojang/behavior_packs"
RESOURCE_PATH="Documents/games/com.mojang/resource_packs"
TARGET_TITLE="Redstone (Survival)"
TARGET_BEHAVIOR_UUID="00000000-0000-4000-8000-000000000001"
SHARED_BEHAVIOR_UUID="00000000-0000-4000-8000-000000000002"
UNREFERENCED_BEHAVIOR_UUID="00000000-0000-4000-8000-000000000003"
UNTRUSTED_BEHAVIOR_UUID="00000000-0000-4000-8000-000000000004"
TARGET_RESOURCE_UUID="00000000-0000-4000-8000-000000000005"
UNREFERENCED_RESOURCE_UUID="00000000-0000-4000-8000-000000000006"
CASE_ROOT=""
OUTPUT_PATH="$TEST_ROOT/output.txt"

mkdir -p "$MOCK_BIN"
trap 'rm -rf "$TEST_ROOT"' EXIT

fail() {
    echo "FAIL: $1" >&2
    if [[ -f "$OUTPUT_PATH" ]]; then cat "$OUTPUT_PATH" >&2; fi
    exit 1
}

assert_exists() {
    [[ -e "$1" ]] || fail "expected path to remain: $1"
}

assert_missing() {
    [[ ! -e "$1" ]] || fail "expected path to be removed: $1"
}

expect_cleanup_failure() {
    local description="$1"
    if run_cleanup; then
        fail "cleanup unexpectedly succeeded: $description"
    fi
}

expect_cleanup_success() {
    local description="$1"
    if ! run_cleanup; then
        fail "cleanup unexpectedly failed: $description"
    fi
}

run_cleanup() {
    env \
        PATH="$MOCK_BIN:$PATH" \
        FAKE_AFC_ROOT="$CASE_ROOT" \
        FAKE_FAIL_LIST_PATH="${FAKE_FAIL_LIST_PATH:-}" \
        FAKE_PARTIAL_LIST_ENTRY="${FAKE_PARTIAL_LIST_ENTRY:-}" \
        FAKE_FAIL_GET_PATH="${FAKE_FAIL_GET_PATH:-}" \
        CRAFTBERRY_CLEANUP_WORLD_NAME="$TARGET_TITLE" \
        CRAFTBERRY_CLEANUP_WORLD_MATCH_MODE=exact \
        CRAFTBERRY_CLEANUP_PACK_SCOPE=referenced \
        "$CLEANUP_SCRIPT" clean --delete-world --yes >"$OUTPUT_PATH" 2>&1
}

write_empty_pack_refs() {
    local world_dir="$1"
    printf '[]\n' > "$world_dir/world_behavior_packs.json"
    printf '[]\n' > "$world_dir/world_resource_packs.json"
}

write_manifest() {
    local pack_dir="$1" uuid="$2" description="${3:-Generated by Craftberry}"
    mkdir -p "$pack_dir"
    cat > "$pack_dir/manifest.json" <<EOF
{"header":{"uuid":"$uuid","name":"$uuid","description":"$description"}}
EOF
}

create_fixture() {
    CASE_ROOT="$TEST_ROOT/device"
    rm -rf "$CASE_ROOT"
    mkdir -p \
        "$CASE_ROOT/minecraftWorlds/target" \
        "$CASE_ROOT/minecraftWorlds/other" \
        "$CASE_ROOT/behavior_packs" \
        "$CASE_ROOT/resource_packs"

    printf '%s\n' "$TARGET_TITLE" > "$CASE_ROOT/minecraftWorlds/target/levelname.txt"
    printf '%s\n' 'Azure (Survival)' > "$CASE_ROOT/minecraftWorlds/other/levelname.txt"
    cat > "$CASE_ROOT/minecraftWorlds/target/world_behavior_packs.json" <<EOF
[{"pack_id":"$TARGET_BEHAVIOR_UUID"},{"pack_id":"$SHARED_BEHAVIOR_UUID"}]
EOF
    cat > "$CASE_ROOT/minecraftWorlds/target/world_resource_packs.json" <<EOF
[{"pack_id":"$TARGET_RESOURCE_UUID"}]
EOF
    write_empty_pack_refs "$CASE_ROOT/minecraftWorlds/other"
    cat > "$CASE_ROOT/minecraftWorlds/other/world_behavior_packs.json" <<EOF
[{"pack_id":"$SHARED_BEHAVIOR_UUID"}]
EOF

    write_manifest "$CASE_ROOT/behavior_packs/target" "$TARGET_BEHAVIOR_UUID"
    write_manifest "$CASE_ROOT/behavior_packs/shared" "$SHARED_BEHAVIOR_UUID"
    write_manifest "$CASE_ROOT/behavior_packs/unreferenced" "$UNREFERENCED_BEHAVIOR_UUID"
    write_manifest "$CASE_ROOT/behavior_packs/untrusted" "$UNTRUSTED_BEHAVIOR_UUID" "Not generated by Craftberry"
    write_manifest "$CASE_ROOT/resource_packs/target" "$TARGET_RESOURCE_UUID"
    write_manifest "$CASE_ROOT/resource_packs/unreferenced" "$UNREFERENCED_RESOURCE_UUID"

    unset FAKE_FAIL_LIST_PATH FAKE_PARTIAL_LIST_ENTRY FAKE_FAIL_GET_PATH
}

cat > "$MOCK_BIN/afcclient" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
shift 3
operation="$1"
shift
remote_root="${FAKE_AFC_ROOT:?}"

resolve_path() {
    local remote_path="$1"
    printf '%s/%s\n' "$remote_root" "${remote_path#Documents/games/com.mojang/}"
}

case "$operation" in
    ls)
        remote_path="$1"
        if [[ "$remote_path" == "${FAKE_FAIL_LIST_PATH:-}" && -n "${FAKE_FAIL_LIST_PATH:-}" ]]; then
            if [[ -n "${FAKE_PARTIAL_LIST_ENTRY:-}" ]]; then
                printf '%s\n' "$FAKE_PARTIAL_LIST_ENTRY"
            fi
            exit 23
        fi
        for child in "$(resolve_path "$remote_path")"/*; do
            [[ -e "$child" ]] || continue
            basename "$child"
        done
        ;;
    get)
        remote_path="$1"
        if [[ "$remote_path" == "${FAKE_FAIL_GET_PATH:-}" && -n "${FAKE_FAIL_GET_PATH:-}" ]]; then
            exit 24
        fi
        cp "$(resolve_path "$remote_path")" "$2"
        ;;
    rm)
        shift
        rm -rf "$(resolve_path "$1")"
        ;;
    put)
        cp "$1" "$(resolve_path "$2")"
        ;;
    *)
        echo "unsupported fake AFC operation: $operation" >&2
        exit 2
        ;;
esac
EOF
chmod +x "$MOCK_BIN/afcclient"

testPartialWorldListingFailureAbortsBeforeMutation() {
    create_fixture
    FAKE_FAIL_LIST_PATH="$WORLD_PATH"
    FAKE_PARTIAL_LIST_ENTRY=target
    expect_cleanup_failure "partial world-directory listing"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/behavior_packs/target"
}

testEmptyWorldListingFailureAbortsBeforeMutation() {
    create_fixture
    FAKE_FAIL_LIST_PATH="$WORLD_PATH"
    FAKE_PARTIAL_LIST_ENTRY=""
    expect_cleanup_failure "world-directory listing failure with empty output"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/behavior_packs/target"
}

testPartialPackListingFailureAbortsBeforeMutation() {
    create_fixture
    FAKE_FAIL_LIST_PATH="$BEHAVIOR_PATH"
    FAKE_PARTIAL_LIST_ENTRY=target
    expect_cleanup_failure "partial behavior-pack listing"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/behavior_packs/target"
}

testPartialResourcePackListingFailureAbortsBeforeMutation() {
    create_fixture
    FAKE_FAIL_LIST_PATH="$RESOURCE_PATH"
    FAKE_PARTIAL_LIST_ENTRY=target
    expect_cleanup_failure "partial resource-pack listing"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/resource_packs/target"
}

testPartialWorldContentsListingFailureAbortsBeforeMutation() {
    create_fixture
    FAKE_FAIL_LIST_PATH="$WORLD_PATH/other"
    FAKE_PARTIAL_LIST_ENTRY=world_behavior_packs.json
    expect_cleanup_failure "partial pack-reference file listing"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/behavior_packs/target"
}

testUnreadableWorldTitlesAbortExactCleanup() {
    create_fixture
    FAKE_FAIL_GET_PATH="$WORLD_PATH/other/levelname.txt"
    expect_cleanup_failure "unreadable unrelated world title"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/minecraftWorlds/other"

    create_fixture
    FAKE_FAIL_GET_PATH="$WORLD_PATH/target/levelname.txt"
    expect_cleanup_failure "unreadable target world title"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
}

testMissingPackReferenceFilesAreEmptyLists() {
    create_fixture
    rm -f \
        "$CASE_ROOT/minecraftWorlds/target/world_behavior_packs.json" \
        "$CASE_ROOT/minecraftWorlds/target/world_resource_packs.json" \
        "$CASE_ROOT/minecraftWorlds/other/world_resource_packs.json"
    expect_cleanup_success "worlds with absent pack-reference files"
    assert_missing "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/minecraftWorlds/other"
    assert_exists "$CASE_ROOT/behavior_packs/target"
    assert_exists "$CASE_ROOT/behavior_packs/shared"
    assert_exists "$CASE_ROOT/resource_packs/target"
}

testEmptyOrWhitespacePackReferencesAbortCleanup() {
    local world file
    for world in target other; do
        create_fixture
        file="$CASE_ROOT/minecraftWorlds/$world/world_behavior_packs.json"
        : > "$file"
        expect_cleanup_failure "empty pack-reference file in $world world"
        assert_exists "$CASE_ROOT/minecraftWorlds/target"
        assert_exists "$CASE_ROOT/behavior_packs/target"

        create_fixture
        file="$CASE_ROOT/minecraftWorlds/$world/world_behavior_packs.json"
        printf ' \t\n' > "$file"
        expect_cleanup_failure "whitespace-only pack-reference file in $world world"
        assert_exists "$CASE_ROOT/minecraftWorlds/target"
        assert_exists "$CASE_ROOT/behavior_packs/target"
    done
}

testMultiplePackReferenceValuesAbortCleanup() {
    local world file
    for world in target other; do
        create_fixture
        file="$CASE_ROOT/minecraftWorlds/$world/world_behavior_packs.json"
        printf '[] []\n' > "$file"
        expect_cleanup_failure "multiple top-level pack-reference values in $world world"
        assert_exists "$CASE_ROOT/minecraftWorlds/target"
        assert_exists "$CASE_ROOT/behavior_packs/target"
    done
}

testUnreadableTargetAndOtherPackReferencesAbortCleanup() {
    create_fixture
    FAKE_FAIL_GET_PATH="$WORLD_PATH/target/world_behavior_packs.json"
    expect_cleanup_failure "unreadable target pack references"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"

    create_fixture
    FAKE_FAIL_GET_PATH="$WORLD_PATH/other/world_resource_packs.json"
    expect_cleanup_failure "unreadable other-world pack references"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/minecraftWorlds/other"
}

testDuplicateExactWorldTitlesAbortCleanup() {
    create_fixture
    mkdir -p "$CASE_ROOT/minecraftWorlds/duplicate"
    printf '%s\n' "$TARGET_TITLE" > "$CASE_ROOT/minecraftWorlds/duplicate/levelname.txt"
    write_empty_pack_refs "$CASE_ROOT/minecraftWorlds/duplicate"
    expect_cleanup_failure "duplicate exact target titles"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/minecraftWorlds/duplicate"
}

testNewlinePackIDAbortsCleanupBeforeMutation() {
    local spoofed_uuid="11111111-1111-4111-8111-111111111111"
    create_fixture
    printf '[{"pack_id":"not-a-uuid\\n%s"}]\n' "$spoofed_uuid" \
        > "$CASE_ROOT/minecraftWorlds/target/world_behavior_packs.json"
    write_manifest "$CASE_ROOT/behavior_packs/newline-spoof" "$spoofed_uuid"

    expect_cleanup_failure "newline-containing pack ID"
    assert_exists "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/behavior_packs/newline-spoof"
    assert_exists "$CASE_ROOT/behavior_packs/target"
    assert_exists "$CASE_ROOT/behavior_packs/shared"
    assert_exists "$CASE_ROOT/resource_packs/target"
}

testOnlyUnsharedTargetPacksAreRemoved() {
    create_fixture
    expect_cleanup_success "target world with a pack shared by another world"
    assert_missing "$CASE_ROOT/minecraftWorlds/target"
    assert_exists "$CASE_ROOT/minecraftWorlds/other"
    assert_missing "$CASE_ROOT/behavior_packs/target"
    assert_exists "$CASE_ROOT/behavior_packs/shared"
    assert_exists "$CASE_ROOT/behavior_packs/unreferenced"
    assert_exists "$CASE_ROOT/behavior_packs/untrusted"
    assert_missing "$CASE_ROOT/resource_packs/target"
    assert_exists "$CASE_ROOT/resource_packs/unreferenced"
}

